#!/usr/bin/env python3
"""Generate PureScript CLI entry points and schemas from lib/cli/catalog.json."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'lib/cli/catalog.json'


def title(name):
    return ''.join(part.capitalize() for part in name.split('-'))


def generated():
    tools = json.loads(CATALOG.read_text())
    blob = json.dumps(tools, separators=(',', ':'), ensure_ascii=True)
    yield ROOT / 'lib/cli/src/CI/CLI/Catalog.purs', '-- Generated by scripts/generate_cli_modules.py.\nmodule CI.CLI.Catalog where\n\ndefinitions :: String\ndefinitions = ' + json.dumps(blob) + '\n'
    host = (ROOT / 'publishing/gemfury/imports.d.ts').read_text().split('declare module "extism:host"', 1)[1]
    for tool in tools:
        directory = ROOT / tool['path']
        exports = [command['name'] for command in tool['commands']]
        module = 'CI.Modules.' + title(tool['name'])
        source = [f'-- Generated by scripts/generate_cli_modules.py.',f'module {module} ({", ".join(exports)}, planFor) where','',
          'import CI.CLI as CLI','import Data.Argonaut.Core (Json)','import Data.Either (Either)','import Effect (Effect)',
          'import FluentCI.Host.Plan as Plan','import Prelude (Unit)','',
          'planFor :: String -> Json -> Either String Plan.Plan',f'planFor = CLI.makePlan "{tool["name"]}"','']
        for command in exports:
            source += [f'{command} :: Effect Unit', f'{command} = CLI.invoke "{tool["name"]}" "{command}"', '']
        yield directory / f'src/CI/Modules/{title(tool["name"])}.purs', '\n'.join(source)
        yield directory / 'entry.mjs', f'export {{ {", ".join(exports)} }} from "./output/{module}/index.js";\n'
        main = 'declare module "main" {\n' + ''.join(f'  export function {name}(): I32;\n' for name in exports) + '}\n'
        yield directory / 'imports.d.ts', main + 'declare module "extism:host"' + host
        schemas = {}
        for command in tool['commands']:
            properties = {'project':{'type':'string','default':'.','minLength':1},'runDir':{'type':'string','minLength':1},'executable':{'type':'string','minLength':1},'timeoutMs':{'type':'integer','minimum':1,'default':900000}}
            required = ['runDir']
            for field in command['fields']:
                kind = field['kind']
                prop = {'type':'array','items':{'type':'string','minLength':1}} if kind == 'strings' else {'type':kind}
                if kind == 'string': prop['minLength'] = 1
                if kind == 'integer': prop['minimum'] = 0 if field['style'] == 'nonnegative' else 1
                if kind == 'strings' and field['required']: prop['minItems'] = 1
                if field['default'] is not None: prop['default'] = field['default']
                elif field['required']: required.append(field['key'])
                if field['choices']: prop['enum'] = field['choices']
                prop['description'] = field['description']
                properties[field['key']] = prop
            schemas[command['name']] = {'input':{'type':'object','properties':properties,'required':required,'additionalProperties':False},'output':{'type':'string','contentType':'application/json'}}
        yield directory / 'schema.json', json.dumps({'name':tool['name'],'exports':schemas},indent=2)+'\n'
        docs=[f'# {tool["title"]} module arguments','', 'Generated from [the CLI catalog](../../lib/cli/catalog.json).','',
              'Every export requires a fresh `runDir`. Common fields are `project` (default `.`),',
              '`executable` (the CLI program or path), and `timeoutMs` (default `900000`).','']
        for command in tool['commands']:
            docs += [f'## `{command["name"]}`','',command['description'],'', '| Field | Type | CLI argument | Default / required |','| --- | --- | --- | --- |']
            for field in command['fields']:
                default = '`'+json.dumps(field['default'])+'`' if field['default'] is not None else 'Required' if field['required'] else 'Omitted'
                argument = field['flag'] or '<' + field['key'] + '>'
                if field['style'].startswith('prefix:'):
                    argument = (field['flag'] + '=' if field['flag'] else '') + field['style'][7:] + '<value>'
                elif field['style'] == 'separate':
                    argument = field['flag'] + ' <value>'
                elif field['style'] == 'space-list':
                    argument = field['flag'] + ' <values...>'
                elif field['flag'] and field['style'] != 'switch':
                    argument += '=<value>'
                kind = field['kind'] + (' (' + ', '.join(field['choices']) + ')' if field['choices'] else '')
                docs.append(f'| `{field["key"]}` | `{kind}` | `{argument}`' + (' (global)' if field['scope']=='global' else '') + f' | {default} |')
            docs.append('')
        yield directory / 'OPTIONS.md', '\n'.join(docs)


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path,text in generated():
        if args.check:
            if not path.exists() or path.read_text()!=text: raise SystemExit('Stale generated CLI file: '+str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text)
    print('CLI module entry points, schemas, and argument references agree.')
