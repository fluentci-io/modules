#!/usr/bin/env python3
"""Generate versioned setup entry points from the checked-in installer catalog."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def title(name):return ''.join(x.capitalize() for x in name.split('-'))
def generated():
 tools=json.loads((ROOT/'lib/setup/tools.json').read_text())
 blob=json.dumps(tools,separators=(',',':'))
 names=', '.join(json.dumps(t['name']) for t in tools)
 code='-- Generated by scripts/generate_setup_tools.py.\nmodule CI.Setup.ToolCatalog where\n\nnames :: Array String\nnames = [ '+names+' ]\n\ndefinitions :: String\ndefinitions = '+json.dumps(blob)+'\n\ndefaultVersion :: String -> String\ndefaultVersion = case _ of\n'
 for t in tools:
  if t['defaultVersion']!='latest':code+='  '+json.dumps(t['name'])+' -> '+json.dumps(t['defaultVersion'])+'\n'
 code+='  _ -> "latest"\n'
 yield ROOT/'lib/setup/src/CI/Setup/ToolCatalog.purs',code
 for t in tools:
  name=t['name'];mod='CI.Setup.'+title(name);d=ROOT/'setup'/name
  yield d/f'src/CI/Setup/{title(name)}.purs',f'''-- Generated by scripts/generate_setup_tools.py.
module {mod} (setup, setupWith, defaultConfig) where

import Prelude (Unit)
import CI.Setup as Setup
import CI.Setup.Types (Config, Result, defaults)
import Effect (Effect)

defaultConfig :: Config
defaultConfig = defaults "{name}"

setupWith :: Config -> Effect Result
setupWith = Setup.install "{name}"

setup :: Effect Unit
setup = Setup.setup "{name}"
'''
  yield d/'entry.mjs',f'export {{ setup }} from "./output/{mod}/index.js";\n'
  props={'version':{'type':'string','default':t['defaultVersion']},'installDir':{'type':'string'},'packageName':{'type':'string'},'sudo':{'type':'boolean','default':False}}
  if name=='extism':
   for key in ['cliVersion','jsVersion','pythonVersion','xtpVersion','binaryenVersion']:props[key]={'type':'string'}
  yield d/'schema.json',json.dumps({'name':'setup-'+name,'exports':{'setup':{'input':{'type':'object','properties':props,'additionalProperties':False},'output':{'type':'object','properties':{'tool':{'type':'string'},'version':{'type':'string'},'binDir':{'type':'string'},'environment':{'type':'object'}}}}}},indent=2)+'\n'
if __name__=='__main__':
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 for p,s in generated():
  if args.check:
   if not p.exists() or p.read_text()!=s:raise SystemExit('Stale generated setup file: '+str(p.relative_to(ROOT)))
  else:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(s)
 print('Setup sources and schemas agree with the installer catalog.')
