#!/usr/bin/env python3
"""Generate the native service profile catalog consumed by PureScript."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generated():
    profiles=json.loads((ROOT/'lib/services/catalog.json').read_text())
    blob=json.dumps(profiles,separators=(',',':'))
    yield ROOT/'lib/services/src/CI/Services/Catalog.purs','-- Generated by scripts/generate_service_modules.py.\nmodule CI.Services.Catalog where\n\ndefinitions :: String\ndefinitions = '+json.dumps(blob)+'\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path,text in generated():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('Stale service catalog: '+str(path.relative_to(ROOT)))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    print('Native service profiles agree with the PureScript catalog.')
