#!/usr/bin/env python3
"""Generate typed setup imports, local-source locks, and dependency metadata."""
import argparse
import json
import os
from pathlib import Path
import re
import tomllib

ROOT = Path(__file__).resolve().parents[1]
IGNORE = ['/fluentci_modules/', '/.fluentci/dependencies/', '/.fluentci/dependencies.add.guard', '/fluentci.lock.guard']


def definitions():
    registry = tomllib.loads((ROOT / 'fluentci.toml').read_text())['modules']
    modules = {m['name']: m for m in registry}
    catalog = {t['name']: t for t in json.loads((ROOT / 'lib/cli/catalog.json').read_text())}
    tools = {t['name']: t for t in json.loads((ROOT / 'lib/setup/tools.json').read_text())}
    result = {}
    for module in registry:
        name = module['name']
        if module['path'].startswith('setup/'):
            result[name] = [{'alias': 'setup-java', 'program': 'java', 'probe': ['which', 'java']}] if name == 'setup-android' else [{'alias': 'setup-docker', 'program': 'docker', 'probe': ['which', 'docker']}] if name == 'setup-buildx' else []
            continue
        primary = tools.get(name, {}).get('program') or catalog.get(name, {}).get('program')
        if module['path'].startswith('notifications/'):
            dependencies = [{'alias': 'setup-curl', 'program': 'curl', 'probe': ['which', 'curl']}]
        elif name == 'nix-publish':
            dependencies = [{'alias': 'setup-nix', 'program': 'nix', 'probe': ['which', 'nix']}, {'alias': 'setup-bun', 'program': 'bun', 'probe': ['which', 'bun']}, {'alias': 'setup-flakehub-push', 'program': 'flakehub-push', 'probe': ['which', 'flakehub-push']}]
        elif name == 'buildx':
            dependencies = [{'alias': 'setup-docker', 'program': 'docker', 'probe': ['which', 'docker']}, {'alias': 'setup-buildx', 'program': 'docker', 'probe': ['docker', 'buildx', 'version']}]
        else:
            dependencies = [{'alias': 'setup-' + name, 'program': primary, 'probe': ['which', primary]}]
            if name == 'cachix':
                dependencies.insert(0, {'alias': 'setup-nix', 'program': 'nix', 'probe': ['which', 'nix']})
            if any(c.get('program') == 'bun' for c in catalog.get(name, {}).get('commands', [])):
                dependencies.append({'alias': 'setup-bun', 'program': 'bun', 'probe': ['which', 'bun']})
        if name == 'depot':dependencies[0]['probe'] = ['depot', 'version']
        if name == 'flipt':dependencies[0]['probe'] = ['flipt', '--version']
        if name in ['git','gh','glab']:dependencies[0]['probe'] = [name, 'version' if name=='glab' else '--version']
        if name in ['gh','glab']:dependencies.append({'alias':'setup-git','program':'git','probe':['git','--version']})
        for d in dependencies:
            if d['alias'] not in modules or not d['program']:
                raise ValueError(f'{name}: missing setup dependency {d}')
        result[name] = dependencies
    return registry, result


def source(name, requirements):
    lines = ['-- Generated by scripts/generate_module_dependencies.py.',
      'module CI.ModuleDependencies (ensureFor) where', '', 'import Prelude',
      'import Data.Either (Either(..))', 'import Effect (Effect)',
      'import Effect.Exception (throw, try)', 'import FluentCI.Plugin as P']
    if name == 'gh-artifacts':
        lines += ['import Data.String.Common (trim)']
    lines += ['', 'foreign import installDependency :: String -> Effect Unit', '',
      'probe :: Array String -> Effect Unit', 'probe args = do',
      '  result <- P.pipeline "setup-dependency-preflight" # P.exec args # P.stdout',
      '  case result of', '    Left error -> throw (P.errorMessage error)', '    Right _ -> pure unit', '',
      'ensure :: String -> Array String -> Effect Unit', 'ensure alias args = do',
      '  present <- try (probe args)', '  case present of', '    Right _ -> pure unit',
      '    Left _ -> do', '      installDependency alias', '      probe args', '',
      'ensureFor :: String -> Effect Unit', 'ensureFor executable = do',
      '  os <- P.getOS >>= case _ of', '    Left error -> throw (P.errorMessage error)', '    Right value -> pure value',
      '  unless (os == "linux" || os == "macos" || os == "freebsd" || os == "openbsd" || os == "netbsd") $',
      '    throw ("Unsupported setup dependency OS: " <> os)']
    call = lambda d: 'ensure ' + json.dumps(d['alias']) + ' [ ' + ', '.join(json.dumps(x) for x in d['probe']) + ' ]'
    if name in ['buildx', 'cachix', 'gh', 'glab']:
        lines += ['  ' + call(d) for d in requirements]
    elif name == 'nix-publish':
        lines += ['  ' + call(requirements[0])]
        for d in requirements[1:]:
            lines += ['  when (executable == ' + json.dumps(d['program']) + ') $ ' + call(d)]
    else:
        main = requirements[0]
        if name in ['scorecard', 'snyk', 'gitlab-artifacts']:
            lines += ['  when (executable /= "bun") $ ' + call(main)]
        else:
            lines += ['  ' + call(main)]
        for d in requirements[1:]:
            lines += ['  when (executable == ' + json.dumps(d['program']) + ') $ ' + call(d)]
        if name == 'gh-artifacts':
            lines += ['  when (executable == "bun") $ do',
              '    available <- P.hasEnv "FLUENTCI_GH_ARTIFACT_CLIENT" >>= case _ of',
              '      Left error -> throw (P.errorMessage error)', '      Right value -> pure value',
              '    location <-', '      if available then do', '        result <- P.getEnv "FLUENTCI_GH_ARTIFACT_CLIENT"',
              '        case result of', '          Left error -> throw (P.errorMessage error)', '          Right value -> pure value',
              '      else pure ""', '    when (trim location == "") $ do', '      installDependency "setup-gh-artifacts"', '      configured <- P.getEnv "FLUENTCI_GH_ARTIFACT_CLIENT"', '      case configured of', '        Right value | trim value /= "" -> pure unit', '        _ -> throw "setup-gh-artifacts did not configure the artifact client SDK"']
        alternatives = {'cmake': ['ctest'], 'rustfmt': ['cargo']}.get(name, [])
        for program in alternatives:
            lines += ['  when (executable == ' + json.dumps(program) + ') $ ensure ' + json.dumps(main['alias']) + ' [ "which", ' + json.dumps(program) + ' ]']
    for program in {'dpkg':['dpkg','realpath'],'rpmbuild':['rpmspec','rpm','realpath']}.get(name,[]):
        lines += ['  ensure '+json.dumps(requirements[0]['alias'])+' [ \"which\", '+json.dumps(program)+' ]']
    if name in ['buildx', 'cachix', 'gh', 'glab'] or (len(requirements) == 1 and name not in ['cmake', 'rustfmt']):
        lines = [line.replace('ensureFor executable = do', 'ensureFor _ = do') for line in lines]
    return '\n'.join(lines) + '\n'


def generated():
    registry, dependencies = definitions()
    modules = {m['name']: m for m in registry}
    for module in registry:
        name, path = module['name'], ROOT / module['path']
        setup = module['path'].startswith('setup/')
        manifest_file = path / 'fluentci-module.toml'
        # Preserve manually authored publishing labels, while syncing the registry identity.
        existing = tomllib.loads(manifest_file.read_text()) if manifest_file.exists() else {}
        values = {k: existing[k] for k in ['description', 'repository', 'readme_url', 'logo', 'topics', 'os', 'arch'] if k in existing}
        lines = [f'name = {json.dumps(name)}', f'version = {json.dumps(module["version"])}', 'license = "MIT"', 'sdk = "purescript"', 'runtime = "component"', 'entry = "entry.mjs"', 'artifact = "dist/plugin.wasm"', 'build = ["npm", "run", "build"]']
        for k, v in values.items():
            lines.append(k + ' = ' + json.dumps(v))
        lock = {'lockfileVersion': 1, 'modules': {}, 'packages': {}, 'git': {}}
        if dependencies[name]:
            lines += ['', '[dependencies]']
        for d in dependencies[name]:
            relative = Path(os.path.relpath(ROOT / modules[d['alias']]['path'], path)).as_posix()
            lines.append(d['alias'] + ' = { path = ' + json.dumps(relative) + ', sdk = "purescript", runtime = "component" }')
            declaration = f'name = "{d["alias"]}"\nruntime = "component"\npath = "{relative}"\nsdk = "purescript"\n'
            lock['modules']['dependency::' + d['alias']] = 'path:' + declaration
        # A companion may itself depend on another installer. Frozen locks must
        # include those declarations under the companion's source directory.
        def nested(owner, seen):
            for requirement in dependencies[owner]:
                alias = requirement['alias']
                if alias in seen:
                    continue
                seen.add(alias)
                source = ROOT / modules[alias]['path']
                source_relative = Path(os.path.relpath(source, path)).as_posix()
                for child in dependencies[alias]:
                    target = Path(os.path.relpath(ROOT / modules[child['alias']]['path'], source)).as_posix()
                    declaration = f'name = "{child["alias"]}"\nruntime = "component"\npath = "{source_relative}/{target}"\nsdk = "purescript"\n'
                    lock['modules'][f'dependency:{source_relative}:{child["alias"]}'] = 'path:' + declaration
                nested(alias, seen)
        nested(name, {name})
        lock['modules'] = dict(sorted(lock['modules'].items()))
        yield manifest_file, '\n'.join(lines) + '\n'
        yield path / 'fluentci.lock', json.dumps(lock, indent=2) + '\n'
        ignore = (path / '.gitignore').read_text()
        for item in IGNORE:
            if item not in ignore.splitlines():
                ignore = ignore.rstrip('\n') + '\n' + item + '\n'
        yield path / '.gitignore', ignore
        if not setup or name == "setup-buildx":
            yield path / 'module-dependencies.json', json.dumps({'module': name, 'requirements': dependencies[name]}, indent=2) + '\n'
            yield path / 'src/CI/ModuleDependencies.purs', source(name, dependencies[name])
            imports = [f'import {{ setup as setup{i} }} from "fluentci:dependency/{d["alias"]}";' for i, d in enumerate(dependencies[name])]
            imports += ['', 'const installers = { ' + ', '.join(json.dumps(d['alias']) + ': setup' + str(i) for i, d in enumerate(dependencies[name])) + ' };',
              'export const installDependency = alias => () => {', '  const install = installers[alias];', '  if (!install) throw Error("Unknown setup dependency: " + alias);', '  install({});', '};', '']
            yield path / 'src/CI/ModuleDependencies.js', '\n'.join(imports)
            yield path / 'test/dependencies.test.mjs', 'import {dependencySuite} from "../../../test/dependencies/suite.mjs";\nawait dependencySuite(new URL("../",import.meta.url));\n'
    inventory = {m['name']: [d['alias'] for d in dependencies[m['name']]] for m in registry if dependencies[m['name']]}
    yield ROOT / 'docs/module-dependencies.json', json.dumps(inventory, indent=2) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    count = 0
    for path, content in generated():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Stale module dependency file: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        count += 1
    print(f'Module manifests, locks, and typed setup dependencies agree ({count} files).')
